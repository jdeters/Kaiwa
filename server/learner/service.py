"""Glue between Kaiwa's web app and the learner model.

Every conversation turn (free chat or roleplay, typed or spoken) is generated by
learner.generate: drafted, validated against the learner profile, repaired,
and only then sent — with kanji shown only for words the learner can read.
The other features (corrections, hints, summaries) use show()/check() so
their Japanese follows the same rules.
"""
import json
import os
import random
import re
import threading
import time
from datetime import datetime

from . import display, generate, grammar, ime, practice, production, validator
from . import profile as profile_store
from .profile import SNAPSHOT_PATH, Profile

OPENER = "(The scene begins. Say your first line.)"
NO_PROFILE = "No learner profile yet — with Anki open, run: .venv/bin/python -m server.learner build"

_lock = threading.Lock()
_cache = {"mtime": None, "profile": None, "concepts": None, "ime": None}


def profile() -> Profile | None:
    """The learner profile, reloaded whenever the snapshot is rebuilt."""
    try:
        mtime = os.path.getmtime(SNAPSHOT_PATH)
    except OSError:
        return None
    with _lock:
        if _cache["mtime"] != mtime:
            _cache.update(mtime=mtime, profile=Profile.load(), concepts=grammar.load_concepts(),
                          ime=None)
        return _cache["profile"]


def status() -> dict:
    p = profile()
    if p is None:
        return {"available": False, "reason": NO_PROFILE}
    snap = p.snapshot
    book = grammar.load_textbook(snap["textbook"])["textbook"]
    return {
        "available": True,
        "textbook": book["title"],
        "lessons_total": book.get("lessons_total", snap["lesson"]),
        "lesson": snap["lesson"],
        "built_at": snap.get("built_at"),
        "words": len(p.lemmas) + sum(1 for w in snap["words"] if w["lemma"].startswith("reading:")),
        "kanji": len(p.kanji),
        "grammar": len(p.grammar),
    }


def rebuild(lesson: int | None = None) -> dict:
    """Re-import from Anki (optionally after changing the finished lesson).
    Raises anki.AnkiError if Anki isn't reachable."""
    cfg = profile_store.load_config()
    if lesson is not None:
        cfg["lesson"] = int(lesson)
    profile_store.save(profile_store.build(cfg))
    if lesson is not None:   # only once the import worked, so config and profile agree
        profile_store.set_config_lesson(lesson)
    return status()   # profile() notices the new snapshot by its mtime


def describe() -> str:
    """One-line description of the learner for analysis prompts."""
    p = profile()
    if p is None:
        return "a beginner"
    title = grammar.load_textbook(p.snapshot["textbook"])["textbook"]["title"]
    return (f"a beginner who has finished lesson {p.snapshot['lesson']} of {title} "
            f"(about {status()['words']} words; polite です/ます style only)")


def _time_of_day() -> str:
    h = datetime.now().hour
    return ("morning" if 5 <= h < 11 else "afternoon" if h < 17 else
            "evening" if h < 22 else "late night")


def scenario_for(session: dict, kaiwa_profile: dict) -> dict:
    """Map a Kaiwa session to a learner.generate scenario."""
    scen = session.get("scenario") or {}
    if session["mode"] in ("roleplay", "practice") and scen:
        out = {"title": scen.get("title", "Roleplay"), "setting": scen.get("setting", ""),
               "ai_role": scen.get("ai_role", ""), "user_role": scen.get("user_role", ""),
               "goal": scen.get("description", "")}
    else:
        out = {"title": "Free chat", "setting": "A relaxed conversation between friends.",
               "ai_role": "A friendly Japanese friend who is curious about the learner.",
               "user_role": "The learner.",
               "goal": "Chat about the learner's day, work, hobbies, and plans."}
    # free chat happens in real time; roleplay and practice scenes set their own
    notes = ([f"It is currently {_time_of_day()} for the learner; greet accordingly, and only "
              "in your first line."] if not scen or session["mode"] == "free_chat"
             else ["Greet as fits the scene's setting, and only in your first line."])
    if kaiwa_profile.get("name"):
        notes.append(f"The learner's name is {kaiwa_profile['name']}.")
    if kaiwa_profile.get("interests"):
        notes.append(f"The learner's interests: {kaiwa_profile['interests']}.")
    notes.append("Your replies may be spoken aloud: no emoji, parentheses, or symbols.")
    if session.get("targets"):
        notes.append(_targets_note(session["targets"]))
    out["notes"] = notes
    return out


# ---------------------------------------------------------------- practice

N_GRAMMAR_TARGETS, N_WORD_TARGETS = 2, 4


def _word_meaning(word_id: str) -> str:
    for w in profile().snapshot["words"]:
        if w["lemma"] == word_id:
            return w.get("meaning", "")
    return ""


def choose_targets(events: list, rng: random.Random | None = None) -> list:
    """Practice targets for a new conversation: a few grammar points and words,
    picked by practice.pick from the learner's observation history."""
    p = profile()
    if p is None:
        return []
    concepts = _cache["concepts"]
    book = grammar.load_textbook(p.snapshot["textbook"])
    # grammar from the newest lessons first (the least automatic); skip
    # word-like concepts and the bare copula, which every sentence uses
    by_lesson = sorted(((int(n), cid) for n, ids in book["lessons"].items() for cid in ids
                        if cid in p.grammar), reverse=True)
    gram = [("grammar", cid) for _, cid in by_lesson
            if concepts.get(cid, {}).get("enforced_by") != "vocabulary" and cid != "copula.desu"]
    words = [("word", w) for w in p.word_list()]
    states = practice.replay(events)
    now = time.time()
    rng = rng or random.Random()
    picked = (practice.pick(gram, states, now, N_GRAMMAR_TARGETS, rng)
              + practice.pick(words, states, now, N_WORD_TARGETS, rng))
    out = []
    for (kind, item), reason in picked:
        if kind == "grammar":
            c = concepts[item]
            out.append({"kind": kind, "item": item, "label": c["name"], "meaning": c["gloss"],
                        "example": c["example"], "reason": reason})
        else:
            out.append({"kind": kind, "item": item, "label": word_label(item),
                        "meaning": _word_meaning(item), "reason": reason})
    return out


SCENE_SCHEMA = {
    "type": "object",
    "properties": {
        "title": {"type": "string"},
        "setting": {"type": "string"},
        "ai_role": {"type": "string"},
        "user_role": {"type": "string"},
        "goal": {"type": "string"},
        "intro": {"type": "string"},
        "targets": {"type": "array", "items": {"type": "string"}},
    },
    "required": ["title", "setting", "ai_role", "user_role", "goal", "intro", "targets"],
    "additionalProperties": False,
}


# Varied everyday settings to draw from: left alone, scene design gravitates to
# restaurants. Each new scene is offered a random few.
SCENE_SETTINGS = [
    "a coworker's desk during a break at the office", "a train station ticket gate",
    "a neighbor's doorstep in your apartment building", "a hobby class (cooking, pottery, guitar…)",
    "a doctor's or dentist's reception desk", "a hotel front desk at check-in",
    "a phone call with a friend making weekend plans", "a park on a sunny morning",
    "a bookstore or library counter", "a gym or swimming pool reception",
    "a friend's home, visiting for the first time", "a taxi ride", "a post office counter",
    "a business meeting introducing yourself to a client", "a bus stop asking about routes",
    "a supermarket checkout", "a clothing store fitting room", "a festival or event booth",
    "an electronics store", "a language exchange meetup", "a school or university office",
    "a hair salon", "a pharmacy", "a lost-and-found counter", "a museum or temple entrance",
    "a garden helping a neighbor", "a car or bike rental shop", "a birthday party",
]


def design_scene(targets: list, client, model: str, recent: list = (),
                 rng: random.Random | None = None) -> tuple:
    """A short roleplay built so that 3–4 of the targets come up naturally.
    recent: titles/settings of the learner's last practice scenes, not to repeat.
    Returns (scenario dict for the session, the targets it uses)."""
    rng = rng or random.Random()
    ideas = "\n".join(f"- {s}" for s in rng.sample(SCENE_SETTINGS, 5))
    avoid = ("\nThe learner's recent practice scenes — use a clearly different place and situation:\n"
             + "\n".join(f"- {r}" for r in recent)) if recent else ""
    listed = "\n".join(
        f"- {t['item']}: {t['label']} — {t['meaning']}" + (f" (e.g. {t['example']})" if t.get("example") else "")
        for t in targets)
    prompt = f"""Design a short everyday roleplay for a Japanese learner: {describe()}.

These are things the learner has studied but rarely says (id: what it is):
{listed}

Pick 3–4 of them that could all come up naturally in ONE plausible, simple everyday situation
(include at least one grammar item if any fits), and design that situation so the learner
will need to say them. The partner (a Japanese speaker) starts the conversation; the learner
replies using only beginner Japanese.

Set it in one of these places (pick the one that fits the targets best), or somewhere equally
different from a restaurant or café:
{ideas}
{avoid}

Return JSON:
- title: short scene title in English
- setting: one sentence, where and when
- ai_role: who the partner plays
- user_role: who the learner plays
- goal: what the learner needs to get across (for the partner; may name the targets)
- intro: 2–3 sentences of ENGLISH, addressed to the learner as "you", setting the scene and
  saying what they want to tell or ask. Describe it in English only — never give the Japanese
  words; working them out is the practice.
- targets: the ids you chose, exactly as listed"""
    resp = generate.create_message(
        client, model, max_tokens=4000,
        output_config={"effort": "low", "format": {"type": "json_schema", "schema": SCENE_SCHEMA}},
        messages=[{"role": "user", "content": prompt}])
    scene = json.loads(next(b.text for b in resp.content if b.type == "text"))
    picked = set(scene.pop("targets", None) or ())
    chosen = [t for t in targets if t["item"] in picked] or targets   # none named: keep all
    scene.update(id="practice", kind="practice", description=scene["goal"])
    return scene, chosen


def _targets_note(targets: list) -> str:
    lines = ["PRACTICE TARGETS — things the learner has studied but rarely says. Over the "
             "conversation, create natural chances for them to use 2–3 of these that fit "
             "the scene (skip any that don't fit):"]
    for t in targets:
        if t["kind"] == "grammar":
            lines.append(f"- grammar {t['label']}: {t['meaning']} e.g. {t['example']}")
        else:
            lines.append(f"- word {t['item'].removeprefix('reading:')}"
                         + (f" ({t['meaning']})" if t.get("meaning") else ""))
    lines.append("Ask questions whose natural answer uses a target, one at a time; never mention "
                 "that these are targets.")
    lines.append("WORD targets: never say the word yourself before the learner does — if you do, "
                 "they just copy it. Ask an open question that makes them reach for it. For 大好き: "
                 "「すしはどうですか。」, not 「すしは大好きですか。」. For 大きい: "
                 "「どんなかばんですか。」, not 「大きいかばんですか。」.")
    lines.append("GRAMMAR targets: your question may use the pattern — asking 「昨日、何を"
                 "しましたか。」 is how you get a past-tense answer.")
    return "\n".join(lines)


def target_report(session: dict, session_obs: list) -> list:
    return practice.report(session.get("targets") or [], session_obs)


def history(db_messages: list) -> list:
    """Kaiwa's stored messages as a Claude conversation (must start with a user turn)."""
    msgs = [{"role": m["role"], "content": m["text"]} for m in db_messages[-24:]]
    if not msgs or msgs[0]["role"] != "user":
        msgs.insert(0, {"role": "user", "content": OPENER})
    return msgs


def reply(session: dict, db_messages: list, kaiwa_profile: dict, client, model: str,
          session_obs: list = ()) -> dict:
    """Generate one validated partner turn. Returns the original text (stored and
    spoken), the learner-facing display, chat-UI tokens, and the translation.
    session_obs: (kind, item, outcome) produced so far — word targets the learner
    hasn't said yet are off-limits to the partner, so they can't just copy them."""
    said = {(k, i) for k, i, _ in session_obs}
    avoid = {t["item"] for t in session.get("targets") or []
             if t["kind"] == "word" and ("word", t["item"]) not in said}
    partner = generate.Partner(profile(), scenario_for(session, kaiwa_profile), model=model,
                               client=client, concepts=_cache["concepts"], avoid=avoid)
    partner.history = history(db_messages)
    t = partner.ai_turn()
    chosen = next((a for a in t.attempts if a["japanese"] == t.japanese), {})   # {} if salvaged
    reading = chosen.get("reading", "")
    return {
        "japanese": t.japanese, "english": t.english,
        "tokens": tokens(t.japanese, reading),
        "meta": {"model": model, "ok": t.ok, "salvaged": t.salvaged, "seconds": t.seconds,
                 "drafts": len(t.attempts), "reading": reading,
                 "cost": round(partner.usage.cost(model), 5)},
    }


def tokens(text: str, reading: str | None = None) -> list:
    """Chat-UI tokens for a partner message (also used when a session is reloaded):
    every kanji kept, with furigana from the model's reading where it fixes UniDic's."""
    return display.kaiwa_tokens(display.render(text, profile(), reading or None, all_kanji=True))


def show(text: str) -> str:
    """Japanese as the learner should see it (unknown kanji → kana)."""
    return display.render(text, profile()).display if text and profile() else text


_JAPANESE_RUN = re.compile(r"[\u3040-\u30ff\u3400-\u9fff々〆ー]+")


def show_quoted(text: str) -> str:
    """English text with any quoted Japanese passed through show()."""
    if not text or profile() is None:
        return text
    return _JAPANESE_RUN.sub(lambda m: show(m.group()), text)


def ime_table() -> dict:
    """Kana → learned-kanji suggestions for the chat input (built once per profile)."""
    p = profile()
    if p is None:
        return {}
    if _cache["ime"] is None:
        _cache["ime"] = ime.table(p)
    return _cache["ime"]


def observe(normalized: str, prev_partner: str, errors: list, hint: bool,
            particles=(), uncertain=()) -> list:
    return production.observe(normalized, profile(), prev_partner, errors, hint, particles, uncertain)


def word_label(word_id: str) -> str:
    """How a tracked word is shown: kana-only words as kana, others by the kanji rule."""
    return word_id[len("reading:"):] if word_id.startswith("reading:") else show(word_id)


def speaking(stat_rows: list, events: list) -> dict:
    """Speaking progress from db.observation_stats(): which known words and grammar
    the learner has produced on their own, which they've studied but never said,
    and what practice would target next (from db.observation_events())."""
    p = profile()
    if p is None:
        return {"available": False}
    items: dict = {}
    for r in stat_rows:
        d = items.setdefault((r["kind"], r["item"]),
                             {**{o: 0 for o in production.OUTCOMES}, "voice": 0, "last": None})
        d[r["outcome"]] += r["n"]
        if r["outcome"] == "independent":
            d["last"] = max(d["last"] or 0, r["last"])
            if r["channel"] == "voice":
                d["voice"] += r["n"]
    words = p.word_list()
    said = [w for w in words if items.get(("word", w), {}).get("independent")]
    concepts = _cache["concepts"]
    gram = []
    for cid in sorted(p.grammar):
        c = concepts.get(cid)
        if not c or c.get("enforced_by") == "vocabulary":
            continue
        d = items.get(("grammar", cid), {})
        gram.append({"id": cid, "name": c["name"], "example": show(c["example"]),
                     **{k: d.get(k, 0) for k in (*production.OUTCOMES, "voice")},
                     "last": d.get("last")})
    return {
        "available": True,
        "words_total": len(words), "words_said": len(said),
        "never_said": [word_label(w) for w in words if w not in said][:60],
        "up_next": choose_targets(events, random.Random(0)),
        "grammar": gram,
    }


def check(text: str) -> validator.Result:
    return validator.validate(text, profile(), _cache["concepts"])
