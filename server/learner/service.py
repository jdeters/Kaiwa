"""Glue between Kaiwa's web app and the learner model.

Every conversation turn (free chat, roleplay, voice call) is generated by
learner.generate: drafted, validated against the learner profile, repaired,
and only then sent — with kanji shown only for words the learner can read.
The other features (corrections, hints, summaries) use show()/check() so
their Japanese follows the same rules.
"""
import os
import re
import threading
from datetime import datetime

from . import display, generate, grammar, ime, validator
from .profile import SNAPSHOT_PATH, Profile

OPENER = "(The scene begins. Say your first line.)"
NO_PROFILE = "No learner profile yet — with Anki open, run: .venv/bin/python -m server.learner build"

_lock = threading.Lock()
_cache = {"mtime": None, "profile": None, "concepts": None, "ime": None}


def profile() -> Profile | None:
    """The learner profile, reloaded whenever the snapshot is rebuilt."""
    try:
        mtime = os.path.getmtime(SNAPSHOT_PATH)
    except OSError:
        return None
    with _lock:
        if _cache["mtime"] != mtime:
            _cache.update(mtime=mtime, profile=Profile.load(), concepts=grammar.load_concepts(),
                          ime=None)
        return _cache["profile"]


def status() -> dict:
    p = profile()
    if p is None:
        return {"available": False, "reason": NO_PROFILE}
    snap = p.snapshot
    return {
        "available": True,
        "textbook": grammar.load_textbook(snap["textbook"])["textbook"]["title"],
        "lesson": snap["lesson"],
        "words": len(p.lemmas) + sum(1 for w in snap["words"] if w["lemma"].startswith("reading:")),
        "kanji": len(p.kanji),
        "grammar": len(p.grammar),
    }


def describe() -> str:
    """One-line description of the learner for analysis prompts."""
    p = profile()
    if p is None:
        return "a beginner"
    title = grammar.load_textbook(p.snapshot["textbook"])["textbook"]["title"]
    return (f"a beginner who has finished lesson {p.snapshot['lesson']} of {title} "
            f"(about {status()['words']} words; polite です/ます style only)")


def _time_of_day() -> str:
    h = datetime.now().hour
    return ("morning" if 5 <= h < 11 else "afternoon" if h < 17 else
            "evening" if h < 22 else "late night")


def scenario_for(session: dict, kaiwa_profile: dict) -> dict:
    """Map a Kaiwa session to a learner.generate scenario."""
    scen = session.get("scenario") or {}
    if session["mode"] == "roleplay" and scen:
        out = {"title": scen.get("title", "Roleplay"), "setting": scen.get("setting", ""),
               "ai_role": scen.get("ai_role", ""), "user_role": scen.get("user_role", ""),
               "goal": scen.get("description", "")}
    else:
        out = {"title": "Free chat", "setting": "A relaxed conversation between friends.",
               "ai_role": "A friendly Japanese friend who is curious about the learner.",
               "user_role": "The learner.",
               "goal": "Chat about the learner's day, work, hobbies, and plans."}
    notes = [f"It is currently {_time_of_day()} for the learner; greet accordingly, and only "
             "in your first line."]
    if kaiwa_profile.get("name"):
        notes.append(f"The learner's name is {kaiwa_profile['name']}.")
    if kaiwa_profile.get("interests"):
        notes.append(f"The learner's interests: {kaiwa_profile['interests']}.")
    if session["mode"] == "call":
        notes.append("This is a voice call: everything you write is spoken aloud. "
                     "No emoji, parentheses, or symbols.")
    out["notes"] = notes
    return out


def history(db_messages: list) -> list:
    """Kaiwa's stored messages as a Claude conversation (must start with a user turn)."""
    msgs = [{"role": m["role"], "content": m["text"]} for m in db_messages[-24:]]
    if not msgs or msgs[0]["role"] != "user":
        msgs.insert(0, {"role": "user", "content": OPENER})
    return msgs


def reply(session: dict, db_messages: list, kaiwa_profile: dict, client, model: str) -> dict:
    """Generate one validated partner turn. Returns the original text (stored and
    spoken), the learner-facing display, chat-UI tokens, and the translation."""
    partner = generate.Partner(profile(), scenario_for(session, kaiwa_profile), model=model,
                               client=client, concepts=_cache["concepts"])
    partner.history = history(db_messages)
    t = partner.ai_turn()
    chosen = next(a for a in t.attempts if a["japanese"] == t.japanese)
    reading = chosen.get("reading", "")
    return {
        "japanese": t.japanese, "display": t.display, "english": t.english,
        "tokens": tokens(t.japanese, reading),
        "meta": {"model": model, "ok": t.ok, "seconds": t.seconds,
                 "drafts": len(t.attempts), "reading": reading,
                 "cost": round(partner.usage.cost(model), 5)},
    }


def tokens(text: str, reading: str | None = None) -> list:
    """Chat-UI tokens for a partner message (also used when a session is reloaded)."""
    return display.kaiwa_tokens(display.render(text, profile(), reading or None))


def show(text: str) -> str:
    """Japanese as the learner should see it (unknown kanji → kana)."""
    return display.render(text, profile()).display if text and profile() else text


_JAPANESE_RUN = re.compile(r"[\u3040-\u30ff\u3400-\u9fff々〆ー]+")


def show_quoted(text: str) -> str:
    """English text with any quoted Japanese passed through show()."""
    if not text or profile() is None:
        return text
    return _JAPANESE_RUN.sub(lambda m: show(m.group()), text)


def ime_table() -> dict:
    """Kana → learned-kanji suggestions for the chat input (built once per profile)."""
    p = profile()
    if p is None:
        return {}
    if _cache["ime"] is None:
        _cache["ime"] = ime.table(p)
    return _cache["ime"]


def check(text: str) -> validator.Result:
    return validator.validate(text, profile(), _cache["concepts"])
